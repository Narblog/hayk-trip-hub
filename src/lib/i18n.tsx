const dicts: Record<Lang, Dict> = {
  en: { ...en, ...extraEn, ...brandEn, ...tourFormEn, ...legalEn, ...cmsEn },
  hy: { ...hy, ...extraHy, ...brandHy, ...tourFormHy, ...legalHy, ...cmsHy },
  ru: { ...ru, ...extraRu, ...brandRu, ...tourFormRu, ...legalRu, ...cmsRu },
};
const enAll: Dict = dicts.en;

type I18nValue = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  localized: <T extends Record<string, unknown>>(row: T | null | undefined, base: string) => string;
};

const I18nContext = createContext<I18nValue | null>(null);
const STORAGE_KEY = "stayland.lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("hy");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (stored && stored in dicts) setLangState(stored);
  }, []);

  const value = useMemo<I18nValue>(() => {
    const setLang = (l: Lang) => {
      setLangState(l);
      window.localStorage.setItem(STORAGE_KEY, l);
      document.documentElement.lang = l;
    };
    const t = (key: string) => dicts[lang][key] ?? enAll[key] ?? key;
    const localized = <T extends Record<string, unknown>>(row: T | null | undefined, base: string) => {
      if (!row) return "";
      return (row[`${base}_${lang}`] as string) ?? (row[`${base}_en`] as string) ?? "";
    };
    return { lang, setLang, t, localized };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

const fallbackI18n: I18nValue = {
  lang: "hy",
  setLang: () => {},
  t: (key: string) => dicts.hy[key] ?? enAll[key] ?? key,
  localized: <T extends Record<string, unknown>>(row: T | null | undefined, base: string) =>
    row ? ((row[`${base}_hy`] as string) ?? (row[`${base}_en`] as string) ?? "") : "",
};

export function useI18n() {
  const ctx = useContext(I18nContext);
  return ctx ?? fallbackI18n;
}